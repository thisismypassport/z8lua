
stringy = "123456789abcdef"

local function countdown(n)
    if (n==0) return
    return n, countdown(n-1)
end

assert(sub(stringy, 4, 8) == "45678", 1)
assert(sub(stringy, -8, -4) == "89abc", 1.1)
assert(sub(stringy, 0, 4) == "1234", 1.2)
assert(sub(stringy, -3, 0) == "", 1.3)
assert(sub(stringy, 100, 100) == "", 1.4)
assert(sub(stringy, 1.9, 1.3) == "1", 1.5)
assert(sub(stringy, 0, 999) == stringy, 1.6)
assert(sub(123, 1, 2) == "12", 1.7)
assert(sub({}, 1, 2) == nil, 1.8)

assert(ord(stringy) == 0x31, 2)
assert(ord(stringy, 1.9) == 0x31, 2.01)
assert(ord(stringy, 4) == 0x34, 2.1)
assert(select('#', ord(stringy, 4)) == 1, 2.11)
assert(ord(stringy, 100) == nil, 2.2)
assert(select('3', ord(stringy, 3, 4)) == 0x35, 2.3)
assert(select('#', ord(stringy, 3, 4)) == 4, 2.31)
assert(ord(stringy, -1) == nil, 2.4)
assert(select('#', ord(stringy, 1, 0)) == 0, 2.5)
assert(select('#', ord(stringy, -1, -1)) == 0, 2.51)
assert(ord(stringy, 0, 4) == nil, 2.6)
assert(select('#', ord(stringy, 0, 4)) == 4, 2.61)
assert(select('1', ord(stringy, 0, 4)) == nil, 2.62)
assert(select('2', ord(stringy, 0, 4)) == 0x31, 2.63)
assert(ord(stringy, 15, 10) == 0x66, 2.7)
assert(select('2', ord(stringy, 15, 10)) == nil, 2.71)
assert(select('#', ord(stringy, 15, 10)) == 10, 2.72)
assert(select('#', ord(stringy, -15, 45)) == 45, 2.73)
assert(ord({}) == nil, 2.8)

assert(chr(99) == "c", 3)
assert(chr(99,100,101) == "cde", 3.1)
assert(chr(0,1,255) == "\0\*\xff", 3.2)
assert(chr(889,-199) == "y9", 3.3)
assert(chr() == "", 3.4)
assert(chr("99",true) == "c\0", 3.5)
assert(#chr(countdown(999)) == 999, 3.6)

local splres = split(",,1,,,big,,,")
assert(splres[1] == '' and splres[2] == '', 4)
assert(splres[3] == 1, 4.01)
assert(splres[4] == '' and splres[5] == '', 4.02)
assert(splres[6] == 'big', 4.03)
assert(splres[7] == '' and splres[8] == '' and splres[9] == '', 4.04)
assert(#splres == 9, 4.05)
assert(#split("") == 1, 4.1)
assert(#split("abc", "") == 3, 4.11)
assert(split("123", "2", false)[1] == "1", 4.2)
assert(split("123", "2", false)[2] == "3", 4.21)
assert(split(stringy, 8)[1] == 0x614e, 4.3)
assert(split(stringy, 8)[2] == "9abcdef", 4.31)
assert(#split(stringy, 0) == 15, 4.4)
assert(split({}) == nil, 4.5)

assert(tostr(nil) == "[nil]", 5)
assert(tostr(false) == "false", 5.01)
assert(tostr(true) == "true", 5.02)
assert(tostr(1234.9) == "1234.9", 5.03)
assert(tostr(-1234.9) == "-1234.9", 5.04)
assert(tostr(0x.0001) == "0", 5.05)
assert(tostr("sdf") == "sdf", 5.06)
assert(tostr({1,2,3}) == "[table]", 5.07)
assert(tostr(tostr) == "[function]", 5.08)
assert(tostr(cocreate(tostr)) == "[thread]", 5.09)
assert(sub(tostr({1,2,3}, 1), 1, 9) == "table: 0x", 5.1)
assert(sub(tostr(tostr, 1), 1, 12) == "function: 0x", 5.11)
assert(tostr(cocreate(tostr), 1) == "[thread]", 5.12)
assert(tostr(false, 1) == "false", 5.13)
assert(tostr(nil, 1) == "[nil]", 5.14)
assert(tostr(1234.5678, 1) == "0x04d2.915b", 5.15)
assert(tostr(-9, 1) == "0xfff7.0000", 5.16)
assert(tostr(1234.5678, 2) == "80908635", 5.2)
assert(tostr(1234.5678, 3) == "0x04d2915b", 5.21)

assert(select('#', tonum("a")) == 0, 6)
assert(select('#', tonum(nil)) == 0, 6.01)
assert(tonum("-1234.5678") == -1234.5678, 6.1)
assert(tonum(true) == 1, 6.11)
assert(tonum(false) == 0, 6.12)
assert(tonum("-0x1234.5678") == -0x1234.5678, 6.13)
assert(tonum("-0b10.01") == -2.25, 6.14)
assert(tonum("12345678", 1) == 0x5678, 6.2)
assert(tonum("12345678", 3) == 0x1234.5678, 6.21)
assert(tonum("fF-f", 1) == 0xff0f, 6.22)
assert(tonum("123456789", 2) == 0x75b.cd15, 6.3)
assert(tonum(true, 2) == 0x.0001, 6.31)
assert(tonum(1, 2) == 1, 6.32)
assert(tonum("abc", 4) == 0, 6.4)
assert(select('#', tonum({}, 4)) == 0, 6.41)
